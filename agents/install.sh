#!/usr/bin/env bash
# Install shared agent instructions from dotfiles into each harness's global location.
# Idempotent: re-running is safe. Existing non-matching files are backed up, never deleted.
#
# Local files, never committed (override the folder with AGENTS_LOCAL_DIR):
#   ~/.config/agents/local.md      Instructions that stay private, such as which skills to load.
#                                  Claude Code imports it; Codex gets it appended (re-run after editing).
#   ~/.config/agents/skills.local  Skill folders to install, one per line. ~ is allowed, # starts a comment.
set -euo pipefail

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LOCAL_DIR="${AGENTS_LOCAL_DIR:-$HOME/.config/agents}"
LOCAL_MD="$LOCAL_DIR/local.md"
SKILLS_LIST="$LOCAL_DIR/skills.local"
GENERATED_MARK="<!-- Generated by dotfiles agents/install.sh."

if [ "$SRC" != "$HOME/.dotfiles/agents" ]; then
  echo "warn     CLAUDE.md imports @~/.dotfiles/agents/AGENTS.md but this repo is at $SRC" >&2
  echo "         Update the import path in $SRC/CLAUDE.md" >&2
fi
if [ "$LOCAL_DIR" != "$HOME/.config/agents" ]; then
  echo "warn     CLAUDE.md imports @~/.config/agents/local.md but AGENTS_LOCAL_DIR is $LOCAL_DIR" >&2
fi

link() {
  local target="$1" dest="$2"
  mkdir -p "$(dirname "$dest")"
  if [ -L "$dest" ] && [ "$(readlink "$dest")" = "$target" ]; then
    echo "ok       $dest"
    return
  fi
  if [ -e "$dest" ] || [ -L "$dest" ]; then
    local backup="$dest.backup.$(date +%Y%m%d%H%M%S)"
    mv "$dest" "$backup"
    echo "backup   $dest -> $backup"
  fi
  ln -s "$target" "$dest"
  echo "linked   $dest -> $target"
}

# Write the given files, one after another, into dest. Used where a harness has no import syntax.
# A file this script generated before is replaced; anything else is backed up first.
build() {
  local dest="$1"; shift
  mkdir -p "$(dirname "$dest")"
  local tmp; tmp="$(mktemp)"
  {
    echo "$GENERATED_MARK Edit the source files and re-run it. -->"
    for f in "$@"; do cat "$f"; echo; done
  } > "$tmp"
  chmod 600 "$tmp"
  if [ -f "$dest" ] && [ ! -L "$dest" ] && cmp -s "$tmp" "$dest"; then
    rm "$tmp"
    echo "ok       $dest"
    return
  fi
  if [ -L "$dest" ]; then
    rm "$dest"
  elif [ -e "$dest" ] && ! head -n 1 "$dest" | grep -qF "$GENERATED_MARK"; then
    local backup="$dest.backup.$(date +%Y%m%d%H%M%S)"
    mv "$dest" "$backup"
    echo "backup   $dest -> $backup"
  fi
  mv "$tmp" "$dest"
  echo "built    $dest"
}

# Link a skill folder. Never moves anything aside, because a backup left in a skills
# folder would load as a second copy of the skill.
link_skill() {
  local target="$1" dest="$2"
  mkdir -p "$(dirname "$dest")"
  if [ -L "$dest" ] && [ "$(readlink "$dest")" = "$target" ]; then
    echo "ok       $dest"
  elif [ -e "$dest" ] || [ -L "$dest" ]; then
    echo "skip     $dest exists and isn't a link to $target; left as it is" >&2
  else
    ln -s "$target" "$dest"
    echo "linked   $dest -> $target"
  fi
}

# Local instructions: created if missing, so the import in CLAUDE.md always resolves.
mkdir -p "$LOCAL_DIR"
if [ ! -e "$LOCAL_MD" ]; then
  echo "<!-- Local agent instructions. Not in the dotfiles repo. -->" > "$LOCAL_MD"
  chmod 600 "$LOCAL_MD"
  echo "created  $LOCAL_MD"
fi

# Codex: global instructions (respects CODEX_HOME). Codex has no import syntax, so the
# public and local instructions are written into one file.
build "${CODEX_HOME:-$HOME/.codex}/AGENTS.md" "$SRC/AGENTS.md" "$LOCAL_MD"

# Claude Code: user-level instructions, which import AGENTS.md and the local file
link "$SRC/CLAUDE.md" "$HOME/.claude/CLAUDE.md"

# Hookdeck: instructions for work under ~/hookdeck/. Skipped if that folder doesn't exist.
if [ -d "$HOME/hookdeck" ]; then
  link "$SRC/hookdeck/AGENTS.md" "$HOME/hookdeck/AGENTS.md"
fi

# Skills from the local list: linked into ~/.agents/skills, and into ~/.claude/skills through it.
if [ -f "$SKILLS_LIST" ]; then
  while IFS= read -r line || [ -n "$line" ]; do
    line="${line%%#*}"
    line="${line#"${line%%[![:space:]]*}"}"
    line="${line%"${line##*[![:space:]]}"}"
    [ -z "$line" ] && continue
    dir="${line/#\~/$HOME}"
    if [ ! -f "$dir/SKILL.md" ]; then
      echo "skip     $dir has no SKILL.md" >&2
      continue
    fi
    name="$(basename "$dir")"
    link_skill "$dir" "$HOME/.agents/skills/$name"
    link_skill "../../.agents/skills/$name" "$HOME/.claude/skills/$name"
  done < "$SKILLS_LIST"
fi

